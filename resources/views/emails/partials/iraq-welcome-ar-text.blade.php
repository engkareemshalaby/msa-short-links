التسجيل عبر منصة «ادرس في مصر»

نود إعلامك بأن فترة التقديم للفصل الدراسي الأول عبر منصة «ادرس في مصر» قد انتهت، بينما لم يُفتح بعد باب التسجيل للفصل الدراسي الثاني (فبراير 2027).

