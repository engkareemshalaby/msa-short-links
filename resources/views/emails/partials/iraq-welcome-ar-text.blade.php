عزيزي الطالب،

يسعدنا أن نلتقي بك في معرض العراق للطلاب ومؤتمر التعليم العالي 2026 في بغداد، ونشكر لك اهتمامك بالانضمام إلى جامعة أكتوبر للعلوم الحديثة والآداب – MSA (أعلى توثيق وشراكة بريطانية في مصر).

يسعدنا إعلامك بأن تسجيلك المبدئي قد وصلنا بنجاح. يرجى اتباع الخطوات التالية لاستكمال إجراءات التقديم.

١. أكمِل تسجيلك عبر منصة «ادرس في مصر»
سجّل بوصفك طالبًا وافدًا من خلال المنصة الرسمية، واختر جامعة MSA:
👉 https://go.msa.edu.eg/iraq-study-in-egypt

٢. تواصل مع الجهات الرسمية في العراق للحصول على المنحة الدراسية الكاملة
بعد استكمال تسجيلك عبر منصة «ادرس في مصر» واختيار جامعة MSA، يرجى تقديم الأوراق والمستندات المطلوبة إلى الجهات الرسمية المختصة في العراق للتقدم للحصول على المنحة الدراسية الكاملة المقدمة من وزارة التعليم العالي والبحث العلمي العراقية والحكومة العراقية.

٣. خصمك الدراسي البالغ 10%
بتسجيلك في معرض الطلاب العراقيين، أصبحت مؤهلًا للحصول على خصم بنسبة 10% على المصروفات الدراسية تُقدمه جامعة MSA مباشرةً لجميع المسجّلين عبر المعرض.

بعد إتمام تسجيلك في منصة «ادرس في مصر» واختيار جامعة MSA، يرجى التقاط Screenshot يوضح إتمام التسجيل بالجامعة، ثم الرد على هذا البريد الإلكتروني وإرفاق صورة الـScreenshot لتأكيد اختيارك للجامعة والاستفادة من الخصم.

