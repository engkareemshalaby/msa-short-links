خصم 10% لطلاب معرض العراق

نتيجة تسجيلك خلال معرض العراق للطلاب 2026، أصبحت مؤهلًا للحصول على خصم بنسبة 10% على المصروفات الدراسية تقدمه جامعة MSA مباشرةً للطلاب المسجلين من خلال المعرض.

سنرسل إليك تفاصيل وخطوات الاستفادة من الخصم في رسالة لاحقة عند فتح باب التسجيل بالمنصة.

