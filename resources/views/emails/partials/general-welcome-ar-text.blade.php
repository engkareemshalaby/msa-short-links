يسعدنا إعلامك بأن تسجيلك المبدئي قد وصلنا بنجاح. يرجى اتباع الخطوات التالية لاستكمال إجراءات التقديم.

١. أكمِل تسجيلك عبر منصة «ادرس في مصر»
سجّل بوصفك طالبًا وافدًا من خلال المنصة الرسمية، واختر جامعة MSA:
👉 https://admission.study-in-egypt.gov.eg/signup

٢. خصمك الدراسي البالغ 10%
بتسجيلك عبر استمارة التسجيل، أصبحت مؤهلًا للحصول على خصم بنسبة 10% على المصروفات الدراسية تُقدمه جامعة MSA مباشرةً لجميع المسجّلين عبر الاستمارة.

بعد إتمام تسجيلك في منصة «ادرس في مصر» واختيار جامعة MSA، يرجى التقاط Screenshot يوضح إتمام التسجيل بالجامعة، ثم الرد على هذا البريد الإلكتروني وإرفاق صورة الـScreenshot لتأكيد اختيارك للجامعة والاستفادة من الخصم.

للاطلاع على تفاصيل شروط القبول والمصروفات الدراسية للطلاب الوافدين والأوراق المطلوبة، يرجى زيارة دليل القبول للطلاب الوافدين:
👉 https://msa.edu.eg/msauniversity/admission-guide/admission-for-international-students/

