عزيزي وليّ الأمر،

سعدنا بلقائكم ونجلكم/نجلتكم خلال معرض العراق للطلاب ومؤتمر التعليم العالي 2026 في بغداد، ونشكركم على اهتمامكم بالانضمام إلى جامعة أكتوبر للعلوم الحديثة والآداب – MSA (أعلى توثيق وشراكة بريطانية في مصر).

يسعدنا تأكيد استلام التسجيل المبدئي لنجلكم/نجلتكم، ونرجو اتباع الخطوات التالية لاستكمال إجراءات التقديم:

١. استكمال التسجيل عبر منصة «ادرس في مصر»
يرجى استكمال تسجيل نجلكم/نجلتكم كطالب وافد عبر المنصة الرسمية «ادرس في مصر»، مع اختيار جامعة MSA:
👉 https://go.msa.edu.eg/iraq-study-in-egypt

٢. تقديم الأوراق المطلوبة إلى الجهات الرسمية في العراق للتقدم للحصول على المنحة الدراسية الكاملة
بعد استكمال التسجيل عبر منصة «ادرس في مصر» واختيار جامعة MSA، يرجى تقديم الأوراق والمستندات المطلوبة إلى الجهات الرسمية المختصة في العراق للتقدم للحصول على المنحة الدراسية الكاملة المقدمة من وزارة التعليم العالي والبحث العلمي العراقية والحكومة العراقية.

٣. خصم بنسبة 10% على المصروفات الدراسية
بموجب تسجيل نجلكم/نجلتكم في معرض العراق للطلاب، أصبح مؤهلًا للحصول على خصم بنسبة 10% على المصروفات الدراسية تقدمه جامعة MSA مباشرةً، وذلك بغض النظر عن حالة الحصول على المنحة الدراسية.

بعد إتمام تسجيلك في منصة «ادرس في مصر» واختيار جامعة MSA، يرجى التقاط Screenshot يوضح إتمام التسجيل بالجامعة، ثم الرد على هذا البريد الإلكتروني وإرفاق صورة الـScreenshot لتأكيد اختيارك للجامعة والاستفادة من الخصم.

للاطلاع على تفاصيل شروط القبول والمصروفات الدراسية للطلاب الوافدين والأوراق المطلوبة، يرجى زيارة دليل القبول للطلاب الوافدين بجامعة MSA:
👉 https://go.msa.edu.eg/iraq-email

