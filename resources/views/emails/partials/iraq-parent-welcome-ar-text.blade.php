عزيزي وليّ الأمر،

نتطلع إلى لقائكم ونجلكم/نجلتكم خلال معرض العراق للطلاب ومؤتمر التعليم العالي 2026 في بغداد، ونشكركم على اهتمامكم بالانضمام إلى جامعة أكتوبر للعلوم الحديثة والآداب (MSA)، صاحبة أعلى توثيق وشراكة بريطانية في مصر.

يسعدنا تأكيد استلام التسجيل المبدئي لنجلكم/نجلتكم، ونود مشاركتكم التعليمات الخاصة باستكمال خطوات التقديم:

التسجيل عبر منصة «ادرس في مصر»

نود إعلامكم بأن فترة التقديم للفصل الدراسي الأول عبر منصة «ادرس في مصر» قد انتهت، بينما لم يُفتح بعد باب التسجيل للفصل الدراسي الثاني (فبراير 2027).

لذلك، لا يلزم نجلكم/نجلتكم اتخاذ أي إجراء عبر المنصة في الوقت الحالي. يرجى متابعة البريد الإلكتروني، حيث سنرسل إليكم رسالة فور فتح باب التسجيل، تتضمن الخطوات المطلوبة لاستكمال الطلب واختيار جامعة MSA.

خصم 10% لطلاب معرض العراق

بفضل تسجيل نجلكم/نجلتكم ضمن معرض العراق للطلاب 2026، أصبح مؤهلًا للحصول على خصم بنسبة 10% على المصروفات الدراسية تقدمه جامعة MSA مباشرةً للطلاب المسجلين من خلال المعرض.

سنرسل إليكم تفاصيل وخطوات الاستفادة من الخصم في رسالة لاحقة عند فتح باب التسجيل عبر المنصة.

المنح الدراسية

إذا كنتم مهتمين بالتقدم للحصول على منحة دراسية كاملة، يرجى متابعة الإعلانات الرسمية الصادرة عن وزارة التعليم العالي والبحث العلمي العراقية والجهات المختصة لمعرفة شروط التقديم والمواعيد والمستندات المطلوبة.

ويمكنكم من الآن التعرف على شروط القبول والمصروفات الدراسية والمستندات المطلوبة من خلال دليل القبول للطلاب الوافدين:
